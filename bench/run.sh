#!/usr/bin/env bash
# bench/run.sh — Run benchmark cases, save per-case outputs with exact CLI commands
set -euo pipefail
cd "$(dirname "$0")"

TOKEN_COUNT="./token-count"
RESULTS="RESULTS.md"
OUTPUT_DIR="outputs"
mkdir -p "$OUTPUT_DIR"

count_tokens() { python3 "$TOKEN_COUNT" <<< "$1"; }

# Init results table
cat > "$RESULTS" << 'EOF'
# Benchmark Results

Generated by `bench/run.sh`. Per-case outputs in `bench/outputs/`.

| Case | Command | Time (ms) | Input Tokens | Output Tokens | Output Lines |
|------|---------|-----------|--------------|---------------|--------------|
EOF

for case_file in cases/*.sh; do
  unset NAME DESCRIPTION commands
  source "$case_file"

  case_slug=$(basename "$case_file" .sh)
  case_md="$OUTPUT_DIR/${case_slug}.md"
  echo "Running: $NAME"

  # Write case header
  cat > "$case_md" << HEADER
# $NAME

$DESCRIPTION

## Results

| Command | Time (ms) | Input Tokens | Output Tokens | Output Lines |
|---------|-----------|--------------|---------------|--------------|
HEADER

  # Collect detail blocks
  details=""

  for cmd in "${commands[@]}"; do
    echo "  → $cmd"
    tmpout=$(mktemp)

    start=$(python3 -c "import time; print(time.time())")
    eval "$cmd" > "$tmpout" 2>/dev/null || true
    end=$(python3 -c "import time; print(time.time())")

    ms=$(python3 -c "print(int(($end - $start) * 1000))")
    output=$(cat "$tmpout")
    out_bytes=$(wc -c < "$tmpout" | tr -d ' ')
    out_tokens=$(count_tokens "$output")
    out_lines=$(wc -l < "$tmpout" | tr -d ' ')
    in_tokens=$(count_tokens "$cmd")
    rm -f "$tmpout"

    # Append to global results
    echo "| $NAME | \`$cmd\` | ${ms}ms | $in_tokens | $out_tokens | $out_lines |" >> "$RESULTS"

    # Append to per-case summary
    echo "| \`$cmd\` | ${ms}ms | $in_tokens | $out_tokens | $out_lines |" >> "$case_md"

    # Collect detail block
    details+="
## \`$cmd\`

Input tokens: $in_tokens | Output tokens: $out_tokens | Time: ${ms}ms | Lines: $out_lines | Bytes: $out_bytes

\`\`\`
$output
\`\`\`
"
  done

  # Write detail blocks after table
  echo "$details" >> "$case_md"
  echo ""
done

echo "Results written to $RESULTS"
echo "Per-case outputs in $OUTPUT_DIR/"
