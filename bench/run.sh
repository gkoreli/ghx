#!/usr/bin/env bash
# bench/run.sh — Run benchmark cases, save outputs, append results to RESULTS.md
set -euo pipefail
cd "$(dirname "$0")"

TOKEN_COUNT="./token-count"
RESULTS="RESULTS.md"
OUTPUT_DIR="outputs"
mkdir -p "$OUTPUT_DIR"

measure() {
  local label="$1" outfile="$2"; shift 2
  local start end ms bytes tokens lines

  start=$(python3 -c "import time; print(time.time())")
  "$@" > "$outfile" 2>/dev/null || true
  end=$(python3 -c "import time; print(time.time())")

  ms=$(python3 -c "print(int(($end - $start) * 1000))")
  bytes=$(wc -c < "$outfile")
  tokens=$(python3 "$TOKEN_COUNT" < "$outfile")
  lines=$(wc -l < "$outfile" | tr -d ' ')

  echo "$label|$ms|$bytes|$tokens|$lines"
}

# Init results table
cat > "$RESULTS" << 'EOF'
# Benchmark Results

Generated by `bench/run.sh`. Per-case outputs saved in `bench/outputs/`.

| Case | Method | Time (ms) | Bytes | Tokens | Lines | API Calls |
|------|--------|-----------|-------|--------|-------|-----------|
EOF

for case_file in cases/*.sh; do
  unset NAME DESCRIPTION cmd_a cmd_b cmd_a_label cmd_b_label cmd_a_calls cmd_b_calls
  source "$case_file"

  case_slug=$(basename "$case_file" .sh)
  echo "Running: $NAME"

  # Run method A
  echo "  → $cmd_a_label..."
  result_a=$(measure "$cmd_a_label" "$OUTPUT_DIR/${case_slug}-a.txt" cmd_a)
  IFS='|' read -r a_label a_ms a_bytes a_tokens a_lines <<< "$result_a"

  # Run method B
  echo "  → $cmd_b_label..."
  result_b=$(measure "$cmd_b_label" "$OUTPUT_DIR/${case_slug}-b.txt" cmd_b)
  IFS='|' read -r b_label b_ms b_bytes b_tokens b_lines <<< "$result_b"

  # Append to results table
  echo "| $NAME | $cmd_a_label | ${a_ms}ms | $a_bytes | $a_tokens | $a_lines | $cmd_a_calls |" >> "$RESULTS"
  echo "| | $cmd_b_label | ${b_ms}ms | $b_bytes | $b_tokens | $b_lines | $cmd_b_calls |" >> "$RESULTS"

  # Write per-case markdown
  cat > "$OUTPUT_DIR/${case_slug}.md" << CASE_EOF
# $NAME

$DESCRIPTION

## Results

| Method | Time (ms) | Bytes | Tokens | Lines | API Calls |
|--------|-----------|-------|--------|-------|-----------|
| $cmd_a_label | ${a_ms}ms | $a_bytes | $a_tokens | $a_lines | $cmd_a_calls |
| $cmd_b_label | ${b_ms}ms | $b_bytes | $b_tokens | $b_lines | $cmd_b_calls |

## Method A: $cmd_a_label

\`\`\`
$(cat "$OUTPUT_DIR/${case_slug}-a.txt")
\`\`\`

## Method B: $cmd_b_label

\`\`\`
$(cat "$OUTPUT_DIR/${case_slug}-b.txt")
\`\`\`
CASE_EOF

  # Clean up raw txt files — the .md has everything
  rm -f "$OUTPUT_DIR/${case_slug}-a.txt" "$OUTPUT_DIR/${case_slug}-b.txt"

  echo "    $cmd_a_label: ${a_ms}ms, $a_tokens tokens"
  echo "    $cmd_b_label: ${b_ms}ms, $b_tokens tokens"
  echo ""
done

echo "Results written to $RESULTS"
echo "Per-case outputs in $OUTPUT_DIR/"
