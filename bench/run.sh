#!/usr/bin/env bash
# bench/run.sh — Run benchmark cases with rate limit awareness
# Code search: 9 req/min = 7s between calls to be safe
set -euo pipefail
cd "$(dirname "$0")"

TOKEN_COUNT="./token-count"
RESULTS="RESULTS.md"
OUTPUT_DIR="outputs"
GHX="$(cd "$(dirname "$0")/.." && pwd)/ghx"  # always use local ghx, not global npm install
RATE_LIMIT_SLEEP=8  # seconds between code search API calls (9 req/min limit)
mkdir -p "$OUTPUT_DIR"

count_tokens() { python3 "$TOKEN_COUNT" <<< "$1"; }

# Init results table
cat > "$RESULTS" << 'EOF'
# Benchmark Results

Generated by `bench/run.sh`. Per-case outputs in `bench/outputs/`.

| Case | Command | Time (ms) | Input Tokens | Output Tokens | Output Lines |
|------|---------|-----------|--------------|---------------|--------------|
EOF

request_count=0

for case_file in cases/*.sh; do
  unset NAME DESCRIPTION commands
  source "$case_file"

  case_slug=$(basename "$case_file" .sh)
  case_md="$OUTPUT_DIR/${case_slug}.md"
  echo "Running: $NAME"

  # Write case header
  cat > "$case_md" << HEADER
# $NAME

$DESCRIPTION

## Results

| Command | Time (ms) | Input Tokens | Output Tokens | Output Lines |
|---------|-----------|--------------|---------------|--------------|
HEADER

  details=""

  for cmd in "${commands[@]}"; do
    # Rate limit: sleep between code search requests
    if (( request_count > 0 )); then
      echo "  ⏳ Rate limit pause (${RATE_LIMIT_SLEEP}s)..."
      sleep "$RATE_LIMIT_SLEEP"
    fi

    echo "  → $cmd"
    tmpout=$(mktemp)
    tmperr=$(mktemp)

    # Substitute 'ghx' with local binary in command execution
    run_cmd="${cmd/ghx/$GHX}"

    start=$(python3 -c "import time; print(time.time())")
    eval "$run_cmd" > "$tmpout" 2>"$tmperr" || true
    end=$(python3 -c "import time; print(time.time())")

    ms=$(python3 -c "print(int(($end - $start) * 1000))")
    output=$(cat "$tmpout")
    stderr_output=$(cat "$tmperr")
    out_bytes=$(wc -c < "$tmpout" | tr -d ' ')
    out_tokens=$(count_tokens "$output")
    out_lines=$(wc -l < "$tmpout" | tr -d ' ')
    in_tokens=$(count_tokens "$cmd")
    rm -f "$tmpout" "$tmperr"
    request_count=$((request_count + 1))

    # Append to global results
    echo "| $NAME | \`$cmd\` | ${ms}ms | $in_tokens | $out_tokens | $out_lines |" >> "$RESULTS"

    # Append to per-case summary
    echo "| \`$cmd\` | ${ms}ms | $in_tokens | $out_tokens | $out_lines |" >> "$case_md"

    # Cap output for readable markdown: 500 chars/line, max 10 lines
    display_output=$(echo "$output" | cut -c1-500 | head -10 || true)
    if (( out_lines > 10 )); then
      display_output+=$'\n'"... (${out_lines} lines total)"
    fi

    # Collect detail block (include stderr for ghx metadata)
    details+="
## \`$cmd\`

Input tokens: $in_tokens | Output tokens: $out_tokens | Time: ${ms}ms | Lines: $out_lines | Bytes: $out_bytes
$(if [[ -n "$stderr_output" ]]; then echo "
**stderr:**
\`\`\`
$stderr_output
\`\`\`"; fi)

**stdout:**
\`\`\`
$display_output
\`\`\`
"
  done

  echo "$details" >> "$case_md"
  echo ""
done

echo "Results written to $RESULTS"
echo "Per-case outputs in $OUTPUT_DIR/"
echo "Total API requests: $request_count (with ${RATE_LIMIT_SLEEP}s spacing)"
